// @ts-check
import netlify from '@astrojs/netlify';
import { defineConfig, envField } from 'astro/config';
import { contentHub } from './src/presentation/astro-integration.ts';

/** Required server secret. Missing or invalid => the app refuses to start (SDD §15). */
const required = (/** @type {object} */ extra = {}) =>
  envField.string({ context: 'server', access: 'secret', ...extra });

/** Optional server secret: becomes required by its phase (docs/DECISIONES.md D-005). */
const optional = () => envField.string({ context: 'server', access: 'secret', optional: true });

// https://astro.build/config
export default defineConfig({
  output: 'server',
  // The app defines no Netlify Edge Functions, so skip their local emulation: it needs Deno,
  // which is not installed by default and crashes `astro dev` when missing.
  adapter: netlify({
    devFeatures: { environmentVariables: false, images: true, edgeFunctions: false },
  }),
  // Registers every route from the registry plus the security middleware (D-010).
  integrations: [contentHub()],
  // Sessions live in our own database (SDD §2), not in Netlify Blobs.
  session: false,
  // Always ship CSS as files, never inline <style>, so styles never depend on CSP hashes (D-026).
  build: { inlineStylesheets: 'never' },
  security: {
    // CSRF protection for POST/PUT/PATCH/DELETE (SDD §2, mandatory).
    checkOrigin: true,
    // Hash-based CSP generated by Astro: no 'unsafe-inline' (SDD §2, §11.2). Directives that a
    // <meta> tag cannot carry (frame-ancestors) are sent as a header by the middleware.
    csp: {
      directives: [
        "default-src 'self'",
        "img-src 'self' data:",
        "connect-src 'self'",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'self'",
      ],
    },
  },
  env: {
    // Validate secrets when the server starts/builds, not lazily on first read.
    validateSecrets: true,
    schema: {
      // --- Required from Phase 0 ---
      DATABASE_URL: required(),
      SESSION_SECRET: required({ min: 32 }),
      ALLOWED_EMAIL_DOMAIN: required({ default: 'holafly.com' }),
      BOOTSTRAP_LEADER_EMAIL: required(),
      PUBLIC_APP_URL: required(),
      AUTH_PROVIDER: envField.enum({
        context: 'server',
        access: 'secret',
        values: ['local', 'atlassian'],
      }),
      // --- Atlassian OAuth 2.0 (login) ---
      ATLASSIAN_CLIENT_ID: optional(),
      ATLASSIAN_CLIENT_SECRET: optional(),
      ATLASSIAN_REDIRECT_URI: optional(),
      // --- Jira (Phase 1) ---
      JIRA_BASE_URL: required(),
      JIRA_EMAIL: required(),
      JIRA_API_TOKEN: required(),
      JIRA_PROJECT_KEY: required(),
      // Custom field ids (defaults live in env-rules.ts; see docs/jira-mapping.md).
      JIRA_FIELD_SLA_RESPONSE: optional(),
      JIRA_FIELD_SLA_DONE: optional(),
      // --- Background sync (D-048) ---
      SYNC_TRIGGER_SECRET: required({ min: 32 }),
      // --- Crowdin (Phase 4) ---
      CROWDIN_TOKEN: optional(),
      CROWDIN_PROJECT_IDS: optional(),
      CROWDIN_WEBHOOK_SECRET: optional(),
      // --- Storage and ingestion (Phases 2-3) ---
      BLOB_READ_WRITE_TOKEN: optional(),
      INGEST_API_TOKEN: optional(),
    },
  },
});
